export type Language = 'zh' | 'en';
export const languageNames = { zh: '简体中文', en: 'English' } as const;

const LanguageContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
  t: typeof zh;
} | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setCurrentLanguage] = useState<Language>('zh');
  const changed = useRef(false);
  const write = useRef(Promise.resolve());

  useEffect(() => {
    let active = true;
    readLanguage().then((value) => {
      if (active && !changed.current && (value === 'zh' || value === 'en')) setCurrentLanguage(value);
    }, () => {});
    return () => { active = false; };
  }, []);

  function setLanguage(next: Language) {
    changed.current = true;
    setCurrentLanguage(next);
    write.current = write.current.then(() => writeLanguage(next)).catch(() => {});
  }

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t: language === 'zh' ? zh : en }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error('LanguageProvider is required.');
  return value;
}
